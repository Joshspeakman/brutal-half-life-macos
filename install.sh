#!/bin/bash
set -euo pipefail
BHL_PROJECT="$(cd "$(dirname "$0")" && pwd)"
BHL_ARCHIVE=''
BHL_VALVE=''
BHL_APP="$HOME/Applications/Brutal Half-Life.app"
BHL_DATA="$HOME/Library/Application Support/Brutal Half-Life"
BHL_CHECK=()
BHL_BRANCH=main
usage() {
    echo 'Usage: ./install.sh --archive /path/to/bhl_v3.zip --valve /path/to/Half-Life/valve [--app /path/to/Brutal Half-Life.app] [--data-dir /path/to/data] [--branch main|nightly] [--check]'
    echo 'The first install keeps the originals a rebuild needs in <data>/game-files; later runs (and the app'"'"'s updates)'
    echo 'can pass that folder as --archive, so the ZIP can be deleted after the first install.'
}
while [[ $# -gt 0 ]]; do
    case "$1" in
        --archive|--valve|--app|--data-dir|--branch)
            [[ $# -ge 2 ]] || { usage >&2; exit 2; }
            case "$1" in
                --archive) BHL_ARCHIVE="$2";;
                --valve) BHL_VALVE="$2";;
                --app) BHL_APP="$2";;
                --data-dir) BHL_DATA="$2";;
                --branch) BHL_BRANCH="$2";;
            esac
            shift 2;;
        --check) BHL_CHECK=(--check --check-client); shift;;
        --help|-h) usage; exit 0;;
        *) usage >&2; exit 2;;
    esac
done
[[ ( -f "$BHL_ARCHIVE" || -d "$BHL_ARCHIVE" ) && -d "$BHL_VALVE" ]] || { usage >&2; exit 2; }
[[ "$BHL_BRANCH" == main || "$BHL_BRANCH" == nightly ]] || { echo '--branch must be main or nightly' >&2; exit 2; }
# Resolve user inputs before changing directory; preserve spaces throughout.
BHL_ARCHIVE="$(cd "$(dirname "$BHL_ARCHIVE")" && pwd)/$(basename "$BHL_ARCHIVE")"
BHL_VALVE="$(cd "$BHL_VALVE" && pwd)"
[[ "$BHL_APP" = /* ]] || BHL_APP="$PWD/$BHL_APP"
[[ "$BHL_DATA" = /* ]] || BHL_DATA="$PWD/$BHL_DATA"
BHL_KEPT="$BHL_DATA/game-files"                         # the originals a rebuild reads, kept beside the install
cd "$BHL_PROJECT"
./bootstrap.sh "$BHL_ARCHIVE"
.venv/bin/python tools/build_project.py --archive "$BHL_ARCHIVE" --valve "$BHL_VALVE" ${BHL_CHECK[@]+"${BHL_CHECK[@]}"}
# The launch window's Updates row: an updater that fetches the branch this app follows from GitHub into a worktree
# of the checkout it was installed from and rebuilds the app there. The worktree shares this checkout's tools and
# build state (.venv, work/), so an update reuses the translation cache and the engine build.
BHL_UPDATER=()
BHL_REPO="$(git -C "$BHL_PROJECT" rev-parse --path-format=absolute --git-common-dir 2>/dev/null || true)"; BHL_REPO="${BHL_REPO%/.git}"
if [[ -n "$BHL_REPO" ]] && git -C "$BHL_REPO" remote get-url origin >/dev/null 2>&1; then
    BHL_BUILT="$(git -C "$BHL_PROJECT" rev-parse HEAD)"
    BHL_WORK=stable; [[ "$BHL_BRANCH" == nightly ]] && BHL_WORK=nightly
    q() { printf '%q' "$1"; }
    BHL_UPDATE_SCRIPT="$(mktemp)"
    cat > "$BHL_UPDATE_SCRIPT" <<UPDATE
#!/bin/bash
# Brutal Half-Life updater (generated by install.sh): "update --check" prints the newest commit of $BHL_BRANCH on
# GitHub; "update" fetches it into a worktree of the checkout this app was installed from and rebuilds the app there.
set -euo pipefail
REPO=$(q "$BHL_REPO"); BRANCH=$BHL_BRANCH; W="\$REPO/build/$BHL_WORK"
export GIT_TERMINAL_PROMPT=0                              # never wait for a password prompt
if [ "\${1:-}" = --check ]; then                          # GitHub's newest, unless this app already has it: a build
  R="\$(git -C "\$REPO" ls-remote origin "refs/heads/\$BRANCH" | cut -f1)"   # from a newer local commit is never offered an older one
  if [ -n "\$R" ] && git -C "\$REPO" merge-base --is-ancestor "\$R" $BHL_BUILT 2>/dev/null; then echo $BHL_BUILT; else echo "\$R"; fi
  exit 0
fi
echo "== fetching \$BRANCH from GitHub"
git -C "\$REPO" fetch -q origin "\$BRANCH"
git -C "\$REPO" worktree prune
if [ -e "\$W/.git" ]; then git -C "\$W" checkout -q -f --detach "origin/\$BRANCH"
else mkdir -p "\$REPO/build"; git -C "\$REPO" worktree add -q -f --detach "\$W" "origin/\$BRANCH"; fi
echo "== \$BRANCH: \$(git -C "\$W" log -1 --format='%h %s')"
for shared in .venv work; do [ -e "\$W/\$shared" ] || ln -s "\$REPO/\$shared" "\$W/\$shared"; done
exec "\$W/install.sh" --archive $(q "$BHL_KEPT") --valve $(q "$BHL_VALVE") --app $(q "$BHL_APP") --data-dir $(q "$BHL_DATA") --branch $BHL_BRANCH
UPDATE
    BHL_UPDATER=(--updater "$BHL_UPDATE_SCRIPT" --branch "$BHL_BRANCH")
fi
echo '== installing the app'
.venv/bin/python tools/package_app.py --archive "$BHL_ARCHIVE" --valve "$BHL_VALVE" --app "$BHL_APP" --data-dir "$BHL_DATA" --replace ${BHL_UPDATER[@]+"${BHL_UPDATER[@]}"}
[[ -n "${BHL_UPDATE_SCRIPT:-}" ]] && rm -f "$BHL_UPDATE_SCRIPT"
if [[ -f "$BHL_ARCHIVE" ]]; then                        # after packaging: a new data folder is made from the whole ZIP
    .venv/bin/python tools/originals.py keep "$BHL_ARCHIVE" "$BHL_KEPT"
    echo "The original ZIP is no longer needed: updates rebuild from $BHL_KEPT"
fi
echo 'Local app built. Open it in Finder to play; no nightly build was published.'
